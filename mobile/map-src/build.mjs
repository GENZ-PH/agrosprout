// Bundles the map page (map-src/main.ts + Leaflet + Terra Draw + Turf) into one
// self-contained HTML string, so the map draws with no network and no CDN (#19).
// Output: src/map/map-html.generated.ts. Run `npm run build:map` after editing map-src/.
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";

const here = import.meta.dirname;
const require = createRequire(import.meta.url);

const result = await build({
  entryPoints: [path.join(here, "main.ts")],
  bundle: true,
  minify: true,
  format: "iife",
  // Android System WebView is evergreen (Chrome); es2019 also covers older phones.
  target: ["es2019"],
  legalComments: "eof",
  write: false,
  logLevel: "warning",
});

const js = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const leafletCss = readFileSync(require.resolve("leaflet/dist/leaflet.css"), "utf8");

const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no">
<title>Map</title>
<base target="_blank">
<style>
${leafletCss}
html, body, #map { margin: 0; width: 100%; height: 100%; background: #3F4A30; }
#map { touch-action: none; }
.lot-label { background: #FFFFFF; color: #1B1F1A; border: 0; border-radius: 8px; box-shadow: none;
  font: 600 13px/1.3 system-ui, -apple-system, Roboto, sans-serif; padding: 3px 8px; }
.lot-label::before { display: none; }
.leaflet-control-attribution { font-size: 10px; }
/* Zoom buttons: 44 px touch targets (Leaflet's default is 30-34 px), below the app's Find me button. */
.leaflet-top.leaflet-right { top: 58px; }
.leaflet-bar a, .leaflet-touch .leaflet-bar a { width: 44px; height: 44px; line-height: 44px; font-size: 22px; }
</style>
</head>
<body>
<div id="map"></div>
<script>${js}</script>
</body>
</html>
`;

const out = path.join(here, "..", "src", "map", "map-html.generated.ts");
writeFileSync(
  out,
  `// GENERATED by map-src/build.mjs from map-src/*.ts. Do not edit by hand.\n` +
    `// Regenerate with \`npm run build:map\` after changing the map page.\n` +
    `export const MAP_HTML = ${JSON.stringify(html)};\n`,
);
console.log(`map page: ${(html.length / 1024).toFixed(0)} KB -> ${path.relative(process.cwd(), out)}`);
