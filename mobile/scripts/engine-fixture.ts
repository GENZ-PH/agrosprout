// Rebuilds the engine test fixture (src/engine/__fixtures__/iligan-lot.fixture.ts)
// from the saved NASA POWER monthly response, using the same parser a live lot
// uses (src/data/power.ts). Run it after power.ts or et0.ts changes, so the
// engine tests run on the values the app actually produces (#32, finding 4).
//   node --disable-warning=MODULE_TYPELESS_PACKAGE_JSON --import ./scripts/node-test-resolve.mjs scripts/engine-fixture.ts
// (from mobile/). It writes one file and fetches nothing.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { parsePowerMonthly } from "../src/data/power";

const RESPONSE_FILE = "power-monthly-8.2N-124.2E-2001-2025.json";
const RESPONSE = join(process.cwd(), "src", "data", "__fixtures__", RESPONSE_FILE);
const OUT = join(process.cwd(), "src", "engine", "__fixtures__", "iligan-lot.fixture.ts");
// The day the saved response was fetched (it was committed with #6, PR #63).
const RETRIEVED = "2026-11-14";

const lot = parsePowerMonthly(JSON.parse(readFileSync(RESPONSE, "utf8")), RETRIEVED, "fixture-iligan");
lot.caveats.unshift("TEST FIXTURE for engine unit tests. Not shipped as demo data.");

const header = [
  "// TEST FIXTURE for engine unit tests. Not demo data; never ship it as real farm data.",
  "// GENERATED by scripts/engine-fixture.ts: do not edit by hand. It is power.ts",
  `// (parsePowerMonthly) run on src/data/__fixtures__/${RESPONSE_FILE},`,
  `// the NASA POWER monthly point response (community AG, ${lot.period}) at 8.2° N, 124.2° E`,
  "// (Iligan area, rounded to 0.1° as live lots are). ET0 from src/data/et0.ts at sea level.",
  'import type { LotData } from "../../types";',
  "",
  `export const ILIGAN_LOT_FIXTURE: LotData = ${JSON.stringify(lot, null, 2)};`,
  "",
].join("\n");

writeFileSync(OUT, header);
console.log(`Wrote ${OUT} (${lot.period}, ${lot.caveats.length} caveats)`);
