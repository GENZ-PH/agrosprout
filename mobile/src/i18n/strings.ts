export const STRINGS: Readonly<Record<Lang, Table>> = { en, fil, ceb };

export type Params = Readonly<Record<string, string | number>>;
/** Looks up one string. Call as t("verdict.first", { goals }). */
export type T = (key: StringKey, params?: Params) => string;

export function translate(lang: Lang, key: StringKey, params?: Params): string {
  const template = STRINGS[lang][key] ?? en[key];
  return params ? template.replace(/\{(\w+)\}/g, (whole, name: string) => (name in params ? String(params[name]) : whole)) : template;
}

export const translator = (lang: Lang): T => (key, params) => translate(lang, key, params);
/** English, the default for pure helpers and tests. */
export const tEn: T = translator("en");

const MONTHS_EN = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"] as const;
const MONTHS_PH = ["Ene", "Peb", "Mar", "Abr", "May", "Hun", "Hul", "Ago", "Set", "Okt", "Nob", "Dis"] as const;
/** Short month names, January first. Filipino and Bisaya share the same short forms. */
export const monthNames = (lang: Lang): readonly string[] => (lang === "en" ? MONTHS_EN : MONTHS_PH);

/** Everyday Filipino crop names. Bisaya names come from the crop library (`local_name`). */
const CROP_FIL: Readonly<Record<string, string>> = {
  "lowland-rice": "Palay",
  corn: "Mais",
  mungbean: "Munggo",
  peanut: "Mani",
  soybean: "Soya",
  "string-bean": "Sitaw",
  "sweet-potato": "Kamote",
  eggplant: "Talong",
};

const short = (name: string) => name.replace(/\s*\(.*\)\s*$/, "").trim() || name;

/** The crop's name in the chosen language, falling back to the English library name, then the id. */
export function cropLabel(lang: Lang, crop: { name: string; local_name?: string | null } | undefined, id: string): string {
  if (!crop) return id;
  if (lang === "fil" && CROP_FIL[id]) return CROP_FIL[id];
  if (lang === "ceb" && crop.local_name) return short(crop.local_name);
  return short(crop.name);
}
